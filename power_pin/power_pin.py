def _qt_enum(cls, *names):
    """Zwraca pierwszy atrybut z listy jaki istnieje na klasie cls."""
    for name in names:
        val = cls
        for part in name.split('.'):
            val = getattr(val, part, None)
            if val is None:
                break
        if val is not None:
            return val
    raise AttributeError(f"Nie znaleziono enuma {names} na {cls}")

QT_USER_ROLE      = _qt_enum(Qt, 'ItemDataRole.UserRole', 'UserRole')
QT_RIGHT_DOCK     = _qt_enum(Qt, 'DockWidgetArea.RightDockWidgetArea', 'RightDockWidgetArea')
QT_CLICK_FOCUS    = _qt_enum(Qt, 'FocusPolicy.ClickFocus', 'ClickFocus')
QT_CHECKED        = _qt_enum(Qt, 'CheckState.Checked', 'Checked')
QT_UNCHECKED      = _qt_enum(Qt, 'CheckState.Unchecked', 'Unchecked')
QT_ITEM_CHECKABLE = _qt_enum(Qt, 'ItemFlag.ItemIsUserCheckable', 'ItemIsUserCheckable')
QT_KEY_ESCAPE     = _qt_enum(Qt, 'Key.Key_Escape', 'Key_Escape')
QT_NO_SELECTION   = _qt_enum(QAbstractItemView, 'SelectionMode.NoSelection', 'NoSelection')
QT_MENU_POPUP     = _qt_enum(QToolButton, 'ToolButtonPopupMode.MenuButtonPopup', 'MenuButtonPopup')

MSG_SUCCESS  = _qt_enum(Qgis, 'MessageLevel.Success', 'Success')
MSG_INFO     = _qt_enum(Qgis, 'MessageLevel.Info', 'Info')
MSG_WARNING  = _qt_enum(Qgis, 'MessageLevel.Warning', 'Warning')
MSG_CRITICAL = _qt_enum(Qgis, 'MessageLevel.Critical', 'Critical')

# QGIS >= 3.30: Qgis.GeometryType, starsze: QgsWkbTypes.*Geometry
GEOM_POINT = _qt_enum(Qgis, 'GeometryType.Point') if hasattr(Qgis, 'GeometryType') \
    else QgsWkbTypes.PointGeometry
GEOM_LINE = _qt_enum(Qgis, 'GeometryType.Line') if hasattr(Qgis, 'GeometryType') \
    else QgsWkbTypes.LineGeometry

QT_RED = QColor('red')


def _log(message, level=None):
    """Wpis do dziennika komunikatów QGIS (zakładka PowerPin)."""
    QgsMessageLog.logMessage(
        message, "PowerPin", MSG_INFO if level is None else level
    )
ICON_TEMPLATE = ':/plugins/power_pin/icons/_{}.png'


