class PowerPin:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        self.iface          = iface
        self.canvas         = iface.mapCanvas()
        self.plugin_dir     = os.path.dirname(__file__)
        self.actions        = []
        self.menu           = self.tr(u'&Power Pin PL')
        self.toolbar        = iface.addToolBar(u'PowerPin')
        self.toolbar.setObjectName(u'PowerPin')
        self.pluginIsActive = False
        self.dockwidget     = None
        self.portals        = []
        self.translator     = None

        # Tryb kompaktowy
        self.split_button        = None
        self.split_button_action = None
        self.compact_action      = None
        self.current_portal      = None

        self.load_portals()

        # Locale
        locale = (QgsSettings().value('locale/userLocale') or 'en')[0:2]
        locale_path = os.path.join(
            self.plugin_dir, 'i18n', f'PowerPin_{locale}.qm'
        )
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Map tool do kopiowania współrzędnych
        self.clickTool = QgsMapToolEmitPoint(self.canvas)
        self.clickTool.canvasClicked.connect(self.canvasClicked)

        # Jedno trwałe narzędzie pinezki na cały czas życia wtyczki.
        # Wcześniej przy każdym wyborze portalu tworzono nowy PointTool,
        # a stary tracił ostatnią referencję Pythona w trakcie podmiany
        # narzędzia na canvasie.
        self.point_tool     = PointTool(self.canvas, self._restore_previous_tool)
        self._previous_tool = None

    # ------------------------------------------------------------------
    # Portale
    # ------------------------------------------------------------------

    def load_portals(self):
        """Wczytaj konfigurację portali z pliku JSON."""
        json_path = os.path.join(self.plugin_dir, 'portals.json')
        try:
            if os.path.exists(json_path):
                with open(json_path, 'r', encoding='utf-8') as f:
                    self.portals = json.load(f)
            else:
                QgsMessageLog.logMessage(
                    f"Portals config not found: {json_path}",
                    "PowerPin", MSG_WARNING
                )
        except ValueError as e:
            # Błąd składni JSON — pokaż go wprost, zamiast po cichu
            # zostawić pustą listę portali.
            msg = f"portals.json: {e}"
            QgsMessageLog.logMessage(msg, "PowerPin", MSG_CRITICAL)
            self.iface.messageBar().pushMessage(
                "Power Pin PL", msg, level=MSG_CRITICAL, duration=0
            )
        except Exception as e:
            QgsMessageLog.logMessage(
                f"Error loading portals: {e}", "PowerPin", MSG_CRITICAL
            )

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def tr(self, message):
        return QCoreApplication.translate('PowerPin', message)

    @staticmethod
    def _portal_name(portal):
        p_id = portal.get('id', '')
        return portal.get('name', p_id.capitalize())

    def add_action(self, icon_path, text, callback, enabled_flag=True,
                   add_to_menu=True, add_to_toolbar=True,
                   status_tip=None, whats_this=None, parent=None):
        icon   = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip  is not None: action.setStatusTip(status_tip)
        if whats_this  is not None: action.setWhatsThis(whats_this)
        if add_to_toolbar:          self.toolbar.addAction(action)
        if add_to_menu:             self.iface.addPluginToWebMenu(self.menu, action)

        self.actions.append(action)
        return action

    # ------------------------------------------------------------------
    # GUI lifecycle
    # ------------------------------------------------------------------

    def _teardown_gui(self):
        """Usuń przyciski z paska i menu (wspólne dla initGui i unload)."""
        for action in self.actions:
            self.iface.removePluginWebMenu(self.menu, action)
            if self.toolbar:
                self.toolbar.removeAction(action)
            action.deleteLater()
        self.actions = []

        if self.split_button_action and self.toolbar:
            self.toolbar.removeAction(self.split_button_action)
        self.split_button_action = None

        if self.split_button:
            # Menu i compact_action są dziećmi split_button — znikną razem z nim
            self.split_button.deleteLater()
        self.split_button   = None
        self.compact_action = None

    def initGui(self):
        """Utwórz wpisy menu i ikony toolbara."""
        self._teardown_gui()

        # Główny przycisk ustawień
        self.main_btn = self.add_action(
            ':/plugins/power_pin/icons/map32.png',
            text=self.tr(u'Power Pin Settings'),
            callback=self.run,
            parent=self.iface.mainWindow()
        )

        settings = QgsSettings()
        self._migrate_legacy_config(settings)

        if settings.value("PowerPin/compact_mode", True, type=bool):
            self.setup_compact_gui(settings)
        else:
            self.setup_expanded_gui(settings)

    def _migrate_legacy_config(self, settings):
        """Jednorazowa migracja starego power_pin_config.txt do QgsSettings."""
        legacy_path = os.path.join(self.plugin_dir, "power_pin_config.txt")
        settings.beginGroup("PowerPin/portals")
        try:
            if os.path.exists(legacy_path) and not settings.allKeys():
                with open(legacy_path, 'r', encoding='utf-8') as f:
                    for line in f:
                        parts = line.strip().split("\t")
                        if len(parts) > 1:
                            settings.setValue(parts[0], parts[1] == "ON")
        except Exception as e:
            _log(f"Legacy config migration failed: {e}", MSG_WARNING)
        finally:
            settings.endGroup()

    def _enabled_portals(self, settings):
        settings.beginGroup("PowerPin/portals")
        enabled = [p for p in self.portals
                   if settings.value(p.get('id'), True, type=bool)]
        settings.endGroup()
        return enabled

    def setup_expanded_gui(self, settings):
        """Klasyczny interfejs — osobny przycisk na każdy portal."""
        for portal in self._enabled_portals(settings):
            self.add_action(
                ICON_TEMPLATE.format(portal.get('id')),
                text=self.tr(self._portal_name(portal)),
                callback=lambda checked=False, p=portal: self.put_pin(p),
                parent=self.iface.mainWindow()
            )

    def setup_compact_gui(self, settings):
        """Interfejs kompaktowy — jeden split button z menu.

        Przycisk ma własną, stałą akcję domyślną (compact_action), która
        uruchamia aktualnie wybrany portal. Akcje z menu tylko zmieniają
        wybrany portal i aktualizują ikonę compact_action. Wcześniej akcja
        domyślna była podmieniana na akcję z tego samego menu wewnątrz jej
        własnego sygnału triggered (w trakcie QMenu.exec), co psuło
        przełączanie portalu.
        """
        self.split_button = QToolButton()
        self.split_button.setFocusPolicy(QT_CLICK_FOCUS)

        menu = QMenu(self.split_button)
        last_used_id = settings.value(
            "PowerPin/last_used_portal", "google", type=str
        )

        enabled = self._enabled_portals(settings)
        current = None
        for portal in enabled:
            p_id = portal.get('id')
            action = QAction(
                QIcon(ICON_TEMPLATE.format(p_id)),
                self.tr(self._portal_name(portal)),
                menu
            )
            action.triggered.connect(
                lambda checked=False, p=portal: self.select_portal(p)
            )
            menu.addAction(action)
            if p_id == last_used_id:
                current = portal

        self.current_portal = current or (enabled[0] if enabled else None)

        self.compact_action = QAction(self.split_button)
        self.compact_action.triggered.connect(
            lambda checked=False: self._run_current_portal()
        )

        self.split_button.setDefaultAction(self.compact_action)
        self.split_button.setMenu(menu)
        self.split_button.setPopupMode(QT_MENU_POPUP)
        self._update_compact_button()

        self.split_button_action = self.toolbar.addWidget(self.split_button)

    def _update_compact_button(self):
        if not self.compact_action:
            return
        portal = self.current_portal
        if portal is None:
            self.compact_action.setEnabled(False)
            self.compact_action.setText(self.tr("No portals"))
            return
        icon = QIcon(ICON_TEMPLATE.format(portal.get('id')))
        name = self.tr(self._portal_name(portal))
        self.compact_action.setEnabled(True)
        self.compact_action.setIcon(icon)
        self.compact_action.setText(name)
        self.compact_action.setToolTip(name)
        if self.split_button:
            self.split_button.setIcon(icon)
            self.split_button.setToolTip(name)

    def _run_current_portal(self):
        if self.current_portal is not None:
            self.put_pin(self.current_portal)

    def unload(self):
        """Usuń elementy GUI z QGIS i posprzątaj narzędzia mapy."""
        self._cleanup_map_tools()
        self._teardown_gui()
        self._cleanup_dock()

        if self.toolbar:
            self.iface.mainWindow().removeToolBar(self.toolbar)
            self.toolbar.deleteLater()
            self.toolbar = None

        if self.translator:
            QCoreApplication.removeTranslator(self.translator)
            self.translator = None

    def _cleanup_map_tools(self):
        """Nie zostawiaj na canvasie narzędzia z wyładowanego modułu."""
        try:
            if self.canvas.mapTool() is self.point_tool:
                self._restore_previous_tool()
            self.canvas.unsetMapTool(self.point_tool)
            self.canvas.unsetMapTool(self.clickTool)
        except Exception as e:
            _log(f"Map tool cleanup failed: {e}", MSG_WARNING)
        self.point_tool.cleanup()
        self._previous_tool = None
        try:
            self.clickTool.canvasClicked.disconnect(self.canvasClicked)
        except (TypeError, RuntimeError):
            pass  # sygnał już odłączony

    def _cleanup_dock(self):
        if self.dockwidget:
            try:
                self.dockwidget.closingPlugin.disconnect(self.onClosePlugin)
            except (TypeError, RuntimeError):
                pass  # sygnał już odłączony
            self.iface.removeDockWidget(self.dockwidget)
            self.dockwidget.deleteLater()
            self.dockwidget = None
        self.pluginIsActive = False

    # ------------------------------------------------------------------
    # Portal actions
    # ------------------------------------------------------------------

    def select_portal(self, portal_config):
        """Wybór portalu z menu w trybie kompaktowym."""
        self.current_portal = portal_config
        QgsSettings().setValue("PowerPin/last_used_portal", portal_config['id'])
        self._update_compact_button()
        self.put_pin(portal_config)

    def use_portal_from_list(self, item):
        """Uruchom portal wybrany dwuklikiem z listy w dockwidget."""
        p_id = item.data(QT_USER_ROLE)
        for portal in self.portals:
            if portal.get('id') == p_id:
                self.put_pin(portal)
                break

    def put_pin(self, portal_config):
        """Aktywuj map tool do wskazania lokalizacji dla danego portalu."""
        p_name = self._portal_name(portal_config)

        msg = "Click on the map to place the pin"
        if portal_config.get('requires_angle', False):
            msg += ", press and drag to set view direction"
        msg += " (Esc = cancel)"

        self.iface.messageBar().pushMessage(
            f"{p_name}:", msg, level=MSG_SUCCESS, duration=3
        )

        dynamic_mode = QgsSettings().value(
            "PowerPin/dynamic_view", True, type=bool
        )
        self.point_tool.set_portal(portal_config, dynamic_mode)

        current = self.canvas.mapTool()
        if current is self.point_tool:
            # Zmiana portalu, gdy narzędzie już jest aktywne
            self.point_tool.reset_state()
            return

        # Zapamiętaj poprzednie narzędzie, żeby wrócić do niego po pinezce
        if current is not None and current is not self.clickTool:
            self._previous_tool = current
        self.canvas.setMapTool(self.point_tool)

    def _restore_previous_tool(self):
        """Po postawieniu pinezki (lub Esc) przywróć poprzednie narzędzie.

        Wcześniej narzędzie było tylko zdejmowane (unsetMapTool), przez co
        canvas zostawał bez żadnego narzędzia — mapa nie reagowała na
        przesuwanie i wyglądało to na zawieszenie.
        """
        if self.canvas.mapTool() is not self.point_tool:
            return
        prev, self._previous_tool = self._previous_tool, None
        try:
            if prev is not None and not sip.isdeleted(prev):
                self.canvas.setMapTool(prev)
                return
        except RuntimeError:
            pass
        try:
            self.iface.actionPan().trigger()
        except Exception:
            self.canvas.unsetMapTool(self.point_tool)

    # ------------------------------------------------------------------
    # Clipboard tool
    # ------------------------------------------------------------------

    def canvasClicked(self, point):
        """Kopiuj współrzędne klikniętego punktu do schowka."""
        coords     = f"{point.y():.3f}\t{point.x():.3f}"
        actual_crs = self.canvas.mapSettings().destinationCrs().authid()
        self.canvas.unsetMapTool(self.clickTool)

        QgsMessageLog.logMessage(str(coords), 'Power Clipboard')
        QApplication.clipboard().setText(coords)

        self.iface.messageBar().pushMessage(
            "Copied to clipboard:",
            f"{coords} // {actual_crs}",
            level=MSG_SUCCESS,
            duration=2
        )

    # ------------------------------------------------------------------
    # Config save
    # ------------------------------------------------------------------

    def save_config(self):
        """Zapisz ustawienia z dockwidgetu i odśwież GUI."""
        if not self.dockwidget:
            return

        settings = QgsSettings()
        settings.setValue(
            "PowerPin/dynamic_view",
            self.dockwidget.cb_dynamic_view.isChecked()
        )
        settings.setValue(
            "PowerPin/compact_mode",
            self.dockwidget.cb_compact_mode.isChecked()
        )

        lw = self.dockwidget.listWidget
        settings.beginGroup("PowerPin/portals")
        for i in range(lw.count()):
            item = lw.item(i)
            settings.setValue(
                item.data(QT_USER_ROLE), item.checkState() == QT_CHECKED
            )
        settings.endGroup()

        self.iface.messageBar().pushMessage(
            "Configuration Saved", "GUI Refreshed.",
            level=MSG_INFO, duration=3
        )

        self.initGui()

    # ------------------------------------------------------------------
    # Run / close
    # ------------------------------------------------------------------

    def onClosePlugin(self):
        self.pluginIsActive = False

    def run(self):
        """Otwórz dockwidget z ustawieniami."""
        self.pluginIsActive = True

        if self.dockwidget is None:
            self.dockwidget = PowerPinDockWidget()
            # Sygnały podłączamy tylko raz przy tworzeniu widgetu.
            self.dockwidget.pushButton.clicked.connect(self.save_config)

            # Pole wyboru = widoczność ikony na pasku,
            # dwuklik w nazwę = uruchomienie portalu.
            # (Wcześniej pojedynczy klik jednocześnie przełączał widoczność
            # i uruchamiał narzędzie pinezki.)
            self.dockwidget.listWidget.itemDoubleClicked.connect(
                self.use_portal_from_list
            )
            self.dockwidget.listWidget.setToolTip(self.tr(
                "Checkbox = icon visible on toolbar, double-click = use portal\n"
                "Pole wyboru = ikona widoczna na pasku, dwuklik = użyj portalu"
            ))
            self.dockwidget.pushButton_3.clicked.connect(
                lambda: webbrowser.open_new(
                    'http://github.com/Rzezimioszek/QGIS-power-pin'
                )
            )
            self.dockwidget.closingPlugin.connect(self.onClosePlugin)
            self.iface.addDockWidget(QT_RIGHT_DOCK, self.dockwidget)

        settings = QgsSettings()
        self.dockwidget.cb_dynamic_view.setChecked(
            settings.value("PowerPin/dynamic_view", True, type=bool)
        )
        self.dockwidget.cb_compact_mode.setChecked(
            settings.value("PowerPin/compact_mode", True, type=bool)
        )

        lw = self.dockwidget.listWidget
        lw.clear()
        lw.setSelectionMode(QT_NO_SELECTION)

        settings.beginGroup("PowerPin/portals")
        for portal in self.portals:
            p_id = portal.get('id')
            item = QtWidgets.QListWidgetItem(
                QIcon(ICON_TEMPLATE.format(p_id)), self._portal_name(portal)
            )
            item.setData(QT_USER_ROLE, p_id)
            item.setFlags(item.flags() | QT_ITEM_CHECKABLE)
            item.setCheckState(
                QT_CHECKED if settings.value(p_id, True, type=bool)
                else QT_UNCHECKED
            )
            lw.addItem(item)
        settings.endGroup()

        self.dockwidget.show()
        self.dockwidget.raise_()


