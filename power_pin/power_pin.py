class PointTool(QgsMapTool):
    """Map tool do wskazywania lokalizacji i otwierania URL portalu.

    Jedna instancja na całą wtyczkę — portal ustawiany przez set_portal().
    """

    def __init__(self, canvas, on_finished=None):
        super().__init__(canvas)
        self.canvas        = canvas
        self.on_finished   = on_finished
        self.portal_config = None
        self.dynamic_mode  = True
        self.pressed       = False
        self.point0        = None
        self.point1        = None

        self.rb = QgsRubberBand(canvas, GEOM_POINT)
        self.rb.setColor(QT_RED)
        self.rb.setIconSize(10)
        self.rl = QgsRubberBand(canvas, GEOM_LINE)
        self.rl.setColor(QT_RED)
        self.rl.setWidth(2)

    def set_portal(self, portal_config, dynamic_mode=True):
        self.portal_config = portal_config
        self.dynamic_mode  = dynamic_mode

    def reset_state(self):
        self.pressed = False
        self.point0  = None
        self.point1  = None
        # reset() bez argumentu zmienia typ gumki na linię — podajemy typ jawnie
        self.rb.reset(GEOM_POINT)
        self.rl.reset(GEOM_LINE)

    def cleanup(self):
        """Usuń gumki ze sceny (przy unload wtyczki)."""
        try:
            self.reset_state()
            scene = self.canvas.scene()
            scene.removeItem(self.rb)
            scene.removeItem(self.rl)
        except Exception as e:
            _log(f"Rubber band cleanup failed: {e}", MSG_WARNING)

    def _finish(self):
        self.reset_state()
        if self.on_finished:
            # Podmiana narzędzia dopiero po zakończeniu obsługi zdarzenia
            QTimer.singleShot(0, self.on_finished)

    # -- events -------------------------------------------------------------

    def canvasPressEvent(self, event):
        if self.portal_config is None:
            return
        self.pressed = True
        self.point0  = event.mapPoint()
        self.point1  = None
        self.rb.reset(GEOM_POINT)
        self.rb.addPoint(self.point0)

    def canvasMoveEvent(self, event):
        if not self.pressed:
            return
        self.point1 = event.mapPoint()
        self.rl.reset(GEOM_LINE)
        self.rl.addPoint(self.point0)
        self.rl.addPoint(self.point1)

    def canvasReleaseEvent(self, event):
        if not self.pressed or self.point0 is None:
            return
        self.pressed = False
        if self.point1 is None:
            self.point1 = self.point0
        try:
            self.open_url()
        finally:
            self._finish()

    def keyPressEvent(self, event):
        if event.key() == QT_KEY_ESCAPE:
            self._finish()
            event.accept()
        else:
            event.ignore()

    def deactivate(self):
        """Wywoływane przez QGIS gdy inny map tool przejmuje canvas."""
        self.reset_state()
        super().deactivate()

    # -- helpers -----------------------------------------------------------

    def _get_transform(self, target_crs_authid):
        source_crs = self.canvas.mapSettings().destinationCrs()
        dest_crs   = QgsCoordinateReferenceSystem(target_crs_authid)
        return QgsCoordinateTransform(source_crs, dest_crs, QgsProject.instance())

    def _get_azimuth(self):
        """Azymut geograficzny (0–360°, od północy, zgodnie z ruchem wskazówek).

        Liczony na elipsoidzie, niezależnie od układu mapy. Wcześniej był
        liczony z różnic współrzędnych w układzie mapy — w EPSG:4326 dawało
        to w Polsce błąd rzędu kilkunastu stopni.
        """
        p0, p1 = self.point0, self.point1
        if p1 is None or (p0.x() == p1.x() and p0.y() == p1.y()):
            return 0.0

        project  = QgsProject.instance()
        bearing  = None
        try:
            da = QgsDistanceArea()
            da.setSourceCrs(
                self.canvas.mapSettings().destinationCrs(),
                project.transformContext()
            )
            ellipsoid = project.ellipsoid()
            if not ellipsoid or ellipsoid.upper() == 'NONE':
                ellipsoid = 'EPSG:7030'  # WGS 84
            da.setEllipsoid(ellipsoid)
            bearing = da.bearing(p0, p1)
        except Exception:
            bearing = None

        if bearing is None or math.isnan(bearing):
            # Fallback: azymut płaski w PL-1992
            try:
                tr = self._get_transform('EPSG:2180')
                a, b = tr.transform(p0), tr.transform(p1)
                bearing = math.atan2(b.x() - a.x(), b.y() - a.y())
            except Exception:
                return 0.0

        return round((math.degrees(bearing) + 360.0) % 360.0, 1)

    def _calculate_zoom(self):
        scale = self.canvas.scale()
        if scale <= 0:
            return 18
        return int(max(0, min(21, math.log2(591657550.5 / scale))))

    def open_url(self):
        if not self.portal_config:
            return
        target_crs_authid = self.portal_config.get('crs', 'EPSG:4326')
        url_template      = self.portal_config.get('url')
        if not url_template:
            return

        transform = self._get_transform(target_crs_authid)
        pt        = transform.transform(self.point0)
        angle     = self._get_azimuth()

        if self.dynamic_mode:
            zoom  = self._calculate_zoom()
            scale = round(self.canvas.scale())
            ext   = transform.transformBoundingBox(self.canvas.extent())
            xmin, ymin = ext.xMinimum(), ext.yMinimum()
            xmax, ymax = ext.xMaximum(), ext.yMaximum()
        else:
            zoom  = 19
            scale = 2000
            xmin  = pt.x() - 100
            ymin  = pt.y() - 100
            xmax  = pt.x() + 100
            ymax  = pt.y() + 100

        params = {
            'x': pt.x(), 'y': pt.y(),
            'lat': pt.y(), 'lon': pt.x(),
            'angle': angle,
            'zoom': zoom, 'scale': scale,
            'xmin': xmin, 'ymin': ymin,
            'xmax': xmax, 'ymax': ymax,
        }

        try:
            url = url_template.format(**params)
            QgsMessageLog.logMessage(f"Opening URL: {url}", "PowerPin")
            webbrowser.open_new(url)
        except Exception as e:
            QgsMessageLog.logMessage(
                f"Error formatting URL for {self.portal_config.get('id')}: {e}",
                "PowerPin", MSG_WARNING
            )
